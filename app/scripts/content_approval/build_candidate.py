def ensure_directory(path):
    checker.directory_guard(path.parent)
    try:
        path.mkdir()
    except FileExistsError:
        pass
    checker.directory_guard(path)


def write_new(path, raw):
    checker.directory_guard(path.parent)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0) | getattr(os, "O_NOFOLLOW", 0), 0o600)
    with os.fdopen(fd, "wb") as stream:
        stream.write(raw)
        stream.flush()
        os.fsync(stream.fileno())
    need(sha(read_regular(path)) == sha(raw), "output_drift", "Candidate output changed while writing")


def build_candidate(root, bundle_path, review_path, version):
    """Testable core; CLI always supplies the tool directory as root."""
    result = {"schemaVersion": 1, "jobId": checker.JOB_ID, "status": "rejected", "candidate_only": True, "no_deploy": True, "errors": []}
    output = None
    try:
        root = Path(os.path.abspath(root))
        checker.directory_guard(root)
        bundle_path = relative(bundle_path, "inbox", 3)
        review_path = relative(review_path, "reviews")
        need(review_path.endswith(".json"), "review_path", "Review must be a JSON file under reviews/")
        need(isinstance(version, str) and bool(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,79}", version)), "version", "Use a new ASCII version label of at most 80 characters")
        checker.safe_relative(version, "candidate version")
        bundle, review_file = root / bundle_path, root / review_path
        need(review_file.exists(), "review_missing", "No independent review JSON exists at the selected path")
        review_raw = read_regular(review_file)
        first = machine_check(bundle)
        renderer_hash = sha(read_regular(Path(__file__).absolute()))
        if first.get("contentTier") == "L":
            need(first.get("rendererSha256") == renderer_hash, "renderer_drift", "Mechanical receipt does not bind this renderer")
        bodies = load_payload(bundle, first)
        review = validate_review(review_raw, first, bundle_path, bodies, root)
        need(review["contentDecision"] == "approved", "review_not_approved", "Batch review is not approved")
        rendered = render_html(bodies)
        second = machine_check(bundle)
        same_receipt(first, second)
        need(read_regular(review_file) == review_raw, "review_drift", "Review changed during the build")
        candidate = root / "candidate"
        ensure_directory(candidate)
        company = candidate / first["code"]
        ensure_directory(company)
        output = company / version
        checker.directory_guard(company)
        output.mkdir(exist_ok=False)
        checker.directory_guard(output)
        write_new(output / "index.html", rendered)
        # An interrupted/failed directory without adoption.json is not complete.
        third = machine_check(bundle)
        same_receipt(first, third)
        need(read_regular(review_file) == review_raw, "review_drift", "Review changed after candidate rendering")
        need(sha(read_regular(output / "index.html")) == sha(rendered), "output_drift", "Rendered candidate changed before adoption record")
        record = {"schemaVersion": 1, "jobId": checker.JOB_ID, "code": first["code"], "status": "local_candidate_built", "candidate_only": True, "no_deploy": True,
                  "builtAt": datetime.now(timezone.utc).isoformat(), "bundlePath": bundle_path, "manifestSha256": first["manifestSha256"], "readySha256": first["readySha256"],
                  "verifiedPayloadHashes": first["verifiedPayloadHashes"], "reviewPath": review_path, "reviewSha256": sha(review_raw), "review": review,
                  "output": {"path": "index.html", "sha256": sha(rendered)}, "mechanicalChecks": [first, second, third],
                  "toolHashes": {"build_candidate.py": sha(read_regular(Path(__file__).absolute())), "package_check.py": sha(read_regular(Path(checker.__file__).absolute()))},
                  "limitations": ["Independent approval is a supplied declaration, not authenticated reviewer identity or automatic fact verification.", "Only the local candidate was generated; no website, audio, project source or deployment was changed.", "Revalidate bundle, review and candidate hashes before any separate publication process."]}
        if first.get("contentTier") == "L":
            need(sha(read_regular(Path(__file__).absolute())) == renderer_hash, "renderer_drift", "Renderer changed during candidate build")
            record.update(contentTier="L", rendererSha256=renderer_hash, producer=first["producer"])
        write_new(output / "adoption.json", json_bytes(record))
        result.update(status="local_candidate_built", code=first["code"], candidatePath=output.relative_to(root).as_posix(), htmlSha256=sha(rendered), manifestSha256=first["manifestSha256"], reviewSha256=sha(review_raw))
        if first.get("contentTier") == "L":
            result.update(contentTier="L", rendererSha256=renderer_hash)
    except (BuildError, checker.PackageError, OSError, TypeError, KeyError) as error:
        result["errors"].append({"code": getattr(error, "code", "filesystem_or_schema"), "message": str(error) if isinstance(error, (BuildError, checker.PackageError)) else type(error).__name__ + ": build refused safely"})
        if output is not None and output.exists():
            result["incompleteOrExistingCandidate"] = str(output)
            result["recovery"] = "No files were overwritten or deleted. A directory without a valid adoption.json is incomplete; inspect it and use a new version label."
    return result


def build_batch_candidates(root, review_path, version):
    """One invocation, one shared review, immutable real HTML/adoption per member."""
    result = {"schemaVersion":1, "status":"rejected", "candidate_only":True, "no_deploy":True, "candidates":[], "errors":[]}
    try:
        review_path = relative(review_path, "reviews")
        raw = read_regular(Path(root) / review_path)
        review = checker.parse_json(raw, "batch review")
        need(review.get("kind") == "l_batch_review" and review.get("contentDecision") == "approved", "batch_review", "An approved independent batch review is required")
        env = batch_envelope(root, review["batchEnvelopePath"], review["batchEnvelopeSha256"])
        first = env["members"][0]
        first_receipt = machine_check(Path(root) / first["bundlePath"])
        validated = validate_batch_review(root, review, first_receipt, first["bundlePath"], load_payload(Path(root) / first["bundlePath"], first_receipt))
        excluded = set(validated.get("excludedCodes", []))
        for member in env["members"]:
            if member["code"] in excluded:
                continue
            built = build_candidate(root, member["bundlePath"], review_path, version)
            result["candidates"].append(built)
            need(built["status"] == "local_candidate_built", "batch_build", "A batch candidate failed; retain partial outputs and use a fresh version for retry")
        need(read_regular(Path(root) / review_path) == raw, "review_drift", "Batch review changed while rendering")
        result.update(status="local_batch_candidates_built", batchId=env["batchId"], reviewScope="sampled_batch", browserAccepted=False)
        if excluded:
            result["excludedCodes"] = sorted(excluded)
    except (ValueError, OSError, TypeError, KeyError) as error:
        result["errors"].append({"code":getattr(error, "code", "invalid_batch"), "message":str(error)})
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--review-contract", action="store_true", help="Print the required review JSON fields without building")
    parser.add_argument("--bundle", help="inbox/<code>/<version>, relative to this tool directory")
    parser.add_argument("--review", help="reviews/<review>.json, independent of the input package")
    parser.add_argument("--batch-review", help="Shared independent batch review; builds the eligible envelope subset in one invocation")
    parser.add_argument("--version", help="New immutable candidate version; an existing directory is refused")
    args = parser.parse_args()
    if args.review_contract:
        print(json.dumps(REVIEW_CONTRACT, ensure_ascii=True, indent=2))
        return 0
    if args.batch_review:
        if args.bundle or args.review or not args.version:
            parser.error("--batch-review requires --version and cannot mix --bundle/--review")
        result = build_batch_candidates(ROOT, args.batch_review, args.version)
        print(json.dumps(result, ensure_ascii=True, indent=2))
        return 0 if result["status"] == "local_batch_candidates_built" else 1
    if not all((args.bundle, args.review, args.version)):
        parser.error("--bundle, --review and --version are required")
    result = build_candidate(ROOT, args.bundle, args.review, args.version)
    print(json.dumps(result, ensure_ascii=True, indent=2))
    return 0 if result["status"] == "local_candidate_built" else 1


if __name__ == "__main__":
    raise SystemExit(main())
