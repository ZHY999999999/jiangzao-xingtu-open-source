class BuildError(ValueError):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


def need(condition, code, message):
    if not condition:
        raise BuildError(code, message)


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def relative(value, prefix, count=None):
    value = checker.safe_relative(value, prefix)
    parts = value.split("/")
    need(parts[0] == prefix and len(parts) >= 2 and (count is None or len(parts) == count), "path", "Input must remain inside the required " + prefix + " layout")
    return value


class ValidationObservation:
    """One pass only. No cached filesystem bytes and no persistence across runs.

    Semantic proofs may be reused inside this observation; every actual read is
    hash-bound. The caller must check the complete read set and control inventory
    again before trusting it. A second independent pass gets a new instance.
    """
    def __init__(self, root):
        self.root = Path(os.path.abspath(root))
        self.hashes = {}
        self.conflict = False
        self.envelopes, self.reviews, self.pages = {}, {}, {}
        self.counts = {"envelopeValidations": 0, "reviewValidations": 0, "pageScans": 0}

    def bind(self, path, raw):
        name = Path(os.path.abspath(path)).relative_to(self.root).as_posix()
        digest = sha(raw)
        if name in self.hashes and self.hashes[name] != digest:
            self.conflict = True
        self.hashes[name] = digest
        self.require_stable()

    def require_stable(self):
        need(not self.conflict, "input_drift", "An input changed within the shared validation observation")


_observation = ContextVar("atlas_validation_observation", default=None)


def current_observation(root):
    value = _observation.get()
    if value is not None:
        need(value.root == Path(os.path.abspath(root)), "observation_root", "Cannot share validation across task roots")
    return value


@contextmanager
def validation_observation(root):
    need(_observation.get() is None, "observation_nested", "Each independent validation pass needs a fresh observation")
    value = ValidationObservation(root)
    token = _observation.set(value)
    try:
        yield value
        value.require_stable()
    finally:
        _observation.reset(token)


def read_regular(path, limit=16 * 1024 * 1024):
    checker.directory_guard(path.parent)
    info = path.lstat()
    need(stat.S_ISREG(info.st_mode) and not checker.is_reparse(info), "unsafe_path", "Only a real regular file may be read")
    need(info.st_size <= limit, "oversized", "Input metadata is too large")
    before = checker.identity(info)
    fd = os.open(path, os.O_RDONLY | getattr(os, "O_BINARY", 0) | getattr(os, "O_NOFOLLOW", 0))
    with os.fdopen(fd, "rb") as stream:
        opened = checker.identity(os.fstat(stream.fileno()))
        need(checker.opened_matches_path(opened, before), "input_drift", "Input changed before read")
        raw = stream.read(limit + 1)
        need(len(raw) <= limit and checker.identity(os.fstat(stream.fileno())) == opened and checker.identity(path.lstat()) == before, "input_drift", "Input changed during read")
    observation = _observation.get()
    if observation is not None:
        observation.bind(path, raw)
    return raw


def machine_check(bundle):
    result = checker.check_bundle(bundle)
    need(result["mechanicalPassed"] is True and result["status"] == "awaiting_semantic_review" and not result["errors"], "mechanical_rejected", "Package is incomplete, unstable, or failed mechanical checks: " + ",".join(e["code"] for e in result["errors"]))
    return result


def same_receipt(before, after):
    for key in ("manifestSha256", "readySha256", "verifiedPayloadHashes", "code", "version"):
        need(before[key] == after[key], "input_drift", "Package changed after the approved input was selected")
    for key in ("contentTier", "rendererSha256", "producer"):
        need(before.get(key) == after.get(key), "input_drift", "Tier, renderer or producer changed during validation")


def timestamp(value, label):
    try:
        parsed = datetime.fromisoformat(checker.text(value, label).replace("Z", "+00:00"))
        need(parsed.tzinfo is not None and parsed.utcoffset() is not None, "review_time", "Review time must include a timezone")
        need(parsed.timestamp() <= time.time() + 300, "review_time", "Review time is unexpectedly in the future")
        return parsed
    except ValueError as error:
        if isinstance(error, (BuildError, checker.PackageError)):
            raise
        raise BuildError("review_time", "Expected an ISO timestamp with timezone") from None


def validate_l_review_fields(review, reader, ready, approved):
    if reader.get("contentTier") != "L":
        need("contentTier" not in review and "checks" not in review, "review_tier", "Legacy reviews must retain the legacy contract")
        return
    need(review.get("contentTier") == "L", "review_tier", "L requires an explicitly L review")
    need(checker.text(review["reviewer"], "review.reviewer").casefold() != checker.text(ready["producer"]["id"], "producer.id").casefold(), "self_review", "Producer cannot approve or independently review its own package")
    checks = review.get("checks")
    checker.shape(checks, L_CHECKS, set(), "review.checks")
    for key in sorted(L_CHECKS):
        row = checks[key]
        checker.shape(row, {"decision", "reason"}, set(), "review.checks." + key)
        need(row["decision"] in {"passed", "needs_revision"}, "review_checks", "Unknown reader review decision")
        checker.text(row["reason"], "review.checks." + key + ".reason")
        need(not approved or row["decision"] == "passed", "review_checks", "Approved L review requires all three reader checks to pass")


def validate_review(raw, receipt, bundle_path, bodies, root=None):
    review = checker.parse_json(raw, "review")
    if isinstance(review, dict) and review.get("kind") == "l_batch_review":
        need(root is not None, "batch_root", "Batch review requires the trusted task root")
        return validate_batch_review(root, review, receipt, bundle_path, bodies)
    checker.shape(review, REVIEW_FIELDS, REVIEW_OPTIONAL, "review")
    need(review["contentDecision"] == "approved", "review_not_approved", "A separate explicit approved decision is required")
    need(review["jobId"] == checker.JOB_ID and review["code"] == receipt["code"] and review["bundlePath"] == bundle_path and review["manifestSha256"] == receipt["manifestSha256"], "review_binding", "Review job, company, exact package path and manifest hash must match")
    checker.text(review["reviewer"], "review.reviewer")
    checker.text(review["scope"], "review.scope")
    if "notes" in review:
        checker.string_list(review["notes"], "review.notes")
    ready = checker.parse_json(bodies["ready.json"], "ready.json")
    need(timestamp(review["reviewedAt"], "review.reviewedAt") >= timestamp(ready["completedAt"], "ready.completedAt"), "review_time", "Review must not predate package completion")
    reviewed = set(checker.string_list(review["reviewedClaimIds"], "review.reviewedClaimIds", nonempty=True))
    evidence = checker.parse_json(bodies["evidence.json"], "evidence.json")
    known = {claim["id"].strip() for claim in evidence["claims"]}
    need(reviewed <= known, "review_claim", "Review lists a claim absent from this exact package")
    reader = checker.parse_json(bodies["reader.json"], "reader.json")
    validate_l_review_fields(review, reader, ready, True)
    used = checker.reader_claim_ids(reader)
    missing = sorted(used - reviewed)
    need(not missing, "review_coverage", "Approved review must declare every claim ID referenced by reader answers and business diagram; missing: " + ", ".join(missing))
    return review


def batch_envelope(root, path, expected):
    observation = current_observation(root)
    if observation is None:
        return _batch_envelope_uncached(root, path, expected)
    path = relative(path, "reviews", 4)
    need(sha(read_regular(Path(root) / path)) == expected, "batch_binding", "Batch envelope changed")
    key = (path, expected)
    if key not in observation.envelopes:
        observation.counts["envelopeValidations"] += 1
        observation.envelopes[key] = _batch_envelope_uncached(root, path, expected)
    return copy.deepcopy(observation.envelopes[key])


def _batch_envelope_uncached(root, path, expected):
    """Verify a real controller submission; not a caller-created group of old passes."""
    import uuid
    path = relative(path, "reviews", 4)
    raw = read_regular(Path(root) / path)
    need(sha(raw) == expected, "batch_binding", "Batch envelope changed")
    value = checker.parse_json(raw, "batch envelope")
    checker.shape(value, {"schemaVersion", "kind", "jobId", "contentTier", "batchId", "leaseId", "producer", "industry", "scopeSha256", "authorizationPath", "authorizationSha256", "assignedAt", "submittedAt", "members", "draftInputs", "memberIndustries"}, set(), "batch envelope")
    need(value["kind"] == "l_batch_envelope" and value["jobId"] == checker.JOB_ID and value["contentTier"] == "L", "batch_identity", "Wrong batch identity")
    for key in ("batchId", "leaseId"):
        need(str(uuid.UUID(value[key])) == value[key], "batch_identity", "Canonical batch/lease UUID required")
    need(path == "reviews/batches/" + value["batchId"] + "/batch.json", "batch_path", "Envelope must use its own batch directory")
    checker.shape(value["producer"], {"id", "runId"}, set(), "batch producer")
    checker.text(value["producer"]["id"], "producer.id")
    need(str(uuid.UUID(value["producer"]["runId"])) == value["producer"]["runId"], "batch_identity", "Canonical run UUID required")
    cfg = checker.parse_json(read_regular(Path(root) / "queue-config.json"), "queue config")
    need(cfg.get("targetContentTier") == "L" and cfg["scopeSha256"] == value["scopeSha256"], "batch_scope", "Batch belongs to another frozen scope")
    scope_raw = read_regular(Path(root) / relative(cfg["scopePath"], "migrations"))
    need(sha(scope_raw) == value["scopeSha256"], "batch_scope", "Frozen scope changed")
    industries = {r["code"]: r.get("industry") for r in checker.parse_json(scope_raw, "scope")["companies"]}
    auth_path = relative(value["authorizationPath"], "reviews")
    auth_raw = read_regular(Path(root) / auth_path)
    need(sha(auth_raw) == value["authorizationSha256"], "batch_authority", "Batch authorization changed")
    auth = checker.parse_json(auth_raw, "batch authorization")
    need(auth.get("authority") == "direct_user_message_in_current_thread" and bool(auth.get("supersedesExecutionRequirements")), "batch_authority", "Batch sampling requires the recorded user authorization")
    state = checker.parse_json(read_regular(Path(root) / "queue-state.json"), "queue state")
    saved = state.get("batchReceipts", {}).get(value["batchId"], {})
    need(saved.get("status") == "submitted" and saved.get("envelopePath") == path and saved.get("envelopeSha256") == expected, "batch_submission", "Missing actual controller batch submission")
    need(saved.get("runId") == value["producer"]["runId"] and saved.get("producerId") == value["producer"]["id"] and saved.get("leaseId") == value["leaseId"], "batch_submission", "Batch producing lease mismatch")
    need(timestamp(value["submittedAt"], "batch submitted") >= timestamp(value["assignedAt"], "batch assigned"), "batch_time", "Batch predates assignment")
    members = value["members"]
    need(isinstance(members, list) and 1 <= len(members) <= 50, "batch_members", "Expected 1..50 actual batch members")
    seen = set()
    for row in members:
        checker.shape(row, {"code", "version", "bundlePath", "manifestSha256", "readySha256"}, set(), "batch member")
        need(row["code"] not in seen and row["code"] != cfg["benchmarkCode"] and industries.get(row["code"]) == value["memberIndustries"].get(row["code"]), "batch_members", "Duplicate, excluded or cross-industry batch member")
        seen.add(row["code"])
        need(row["bundlePath"] == f'inbox/{row["code"]}/{row["version"]}', "batch_members", "Batch member path mismatch")
        folder = Path(root) / relative(row["bundlePath"], "inbox", 3)
        manifest_raw, ready_raw = (read_regular(folder / n) for n in ("manifest.json", "ready.json"))
        need(sha(manifest_raw) == row["manifestSha256"] and sha(ready_raw) == row["readySha256"], "batch_member_drift", "A member manifest/ready changed or is absent")
        ready = checker.parse_json(ready_raw, "batch ready")
        need(ready.get("producer") == value["producer"] and ready.get("manifestSha256") == row["manifestSha256"], "batch_producer", "A member has a different producer/run or manifest")
        need(timestamp(value["assignedAt"], "batch assigned") <= timestamp(ready["completedAt"], "member completed") <= timestamp(value["submittedAt"], "batch submitted"), "batch_time", "Member completion must be within the producing assignment/submission interval")
        manifest = checker.parse_json(manifest_raw, "batch manifest")
        for entry in manifest["files"]:
            name = checker.safe_relative(entry["path"], "batch payload path")
            need(sha(read_regular(folder / name)) == entry["sha256"], "batch_member_drift", "A member payload changed")
    need(set(value["memberIndustries"]) == seen and value["memberIndustries"] == saved.get("memberIndustries"), "batch_scope", "Batch member industries differ from assignment")
    industry_values = set(value["memberIndustries"].values())
    need(all(isinstance(v, str) and v.strip() for v in industry_values) and (industry_values == {value["industry"]} or (len(industry_values) > 1 and value["industry"] == "mixed_existing_evidence")), "batch_scope", "Cross-industry batch must retain truthful member industries")
    need([{k:r[k] for k in ("code", "version")} for r in members] == saved.get("members"), "batch_members", "Envelope differs from permanently reserved batch members")
    need(value["draftInputs"] == saved.get("draftInputs", []), "batch_provenance", "Reused draft provenance differs from assignment")
    prior_codes = set()
    for draft in value["draftInputs"]:
        checker.shape(draft, {"code", "bundlePath", "manifestSha256", "readySha256"}, set(), "reused draft")
        need(draft["code"] in seen and draft["code"] not in prior_codes, "batch_provenance", "Reused draft is not a unique batch member")
        prior_codes.add(draft["code"])
        folder = Path(root) / relative(draft["bundlePath"], "inbox", 3)
        need(sha(read_regular(folder / "manifest.json")) == draft["manifestSha256"] and sha(read_regular(folder / "ready.json")) == draft["readySha256"], "batch_provenance", "Original reused draft changed")
        need(draft["bundlePath"] != next(r["bundlePath"] for r in members if r["code"] == draft["code"]), "batch_provenance", "Reused draft must receive a new immutable version")
    return value


def validate_batch_review(root, review, receipt, bundle_path, bodies):
    observation = current_observation(root)
    if observation is None:
        return _validate_batch_review_uncached(root, review, receipt, bundle_path, bodies)
    key = sha(json_bytes(review))
    if key not in observation.reviews:
        result = _validate_batch_review_uncached(root, review, receipt, bundle_path, bodies)
        observation.counts["reviewValidations"] += 1
        # The uncached validator above checked every row, not only this member.
        env = batch_envelope(root, review["batchEnvelopePath"], review["batchEnvelopeSha256"])
        observation.reviews[key] = (copy.deepcopy(review), env)
        return result
    approved_review, env = observation.reviews[key]
    need(receipt.get("contentTier") == "L", "batch_review_scope", "Batch sampling applies only to L")
    selected = next((row for row in approved_review["members"] if row["bundlePath"] == bundle_path), None)
    expected = {row["code"]: row for row in env["members"]}
    need(selected is not None and selected["code"] == receipt["code"] and selected["manifestSha256"] == receipt["manifestSha256"] and expected[selected["code"]]["readySha256"] == receipt["readySha256"], "batch_members", "Package is absent from this batch approval")
    return _batch_member_view(approved_review, env, selected, receipt, bundle_path)


def _batch_member_view(review, env, selected, receipt, bundle_path):
    excluded = set(review.get("excludedCodes", []))
    return {"kind":"l_batch_member_acceptance", "reviewScope":"sampled_batch", "contentDecision":"needs_revision" if selected["code"] in excluded else review["contentDecision"], "reviewer":review["reviewer"].strip(), "reviewedAt":review["reviewedAt"], "scope":review["scope"], "bundlePath":bundle_path, "code":receipt["code"], "manifestSha256":receipt["manifestSha256"], "reviewedClaimIds":list(selected["reviewedClaimIds"]), "contentSampled":selected["contentSampled"], "batchId":env["batchId"], "batchEnvelopePath":review["batchEnvelopePath"], "batchEnvelopeSha256":review["batchEnvelopeSha256"], "authorizationPath":env["authorizationPath"], "authorizationSha256":env["authorizationSha256"], **({"excludedCodes":sorted(excluded)} if excluded else {})}


def _validate_batch_review_uncached(root, review, receipt, bundle_path, bodies):
    checker.shape(review, {"schemaVersion", "kind", "jobId", "contentTier", "reviewScope", "batchId", "batchEnvelopePath", "batchEnvelopeSha256", "contentDecision", "reviewer", "reviewedAt", "sampling", "scope", "members"}, {"excludedCodes"}, "batch review")
    need(review["reviewScope"] == "sampled_batch" and review["contentTier"] == "L" and receipt.get("contentTier") == "L" and review["jobId"] == checker.JOB_ID, "batch_review_scope", "Batch sampling applies only to explicitly batch-produced L")
    need(review["contentDecision"] in {"approved", "needs_revision", "insufficient_evidence"}, "batch_decision", "Unknown batch content decision")
    env = batch_envelope(root, review["batchEnvelopePath"], review["batchEnvelopeSha256"])
    need(review["batchId"] == env["batchId"], "batch_identity", "Review belongs to another batch")
    checker.text(review["scope"], "batch review scope")
    reviewer = checker.text(review["reviewer"], "batch reviewer")
    need(reviewer.casefold() != env["producer"]["id"].strip().casefold(), "self_review", "Batch author cannot approve its own sample")
    need(timestamp(review["reviewedAt"], "batch review time") >= timestamp(env["submittedAt"], "batch submission"), "review_time", "Batch review predates complete submission")
    checker.shape(review["sampling"], {"method", "reason", "riskCodes"}, set(), "sampling")
    checker.text(review["sampling"]["method"], "sample method"); checker.text(review["sampling"]["reason"], "sample reason")
    risk = set(checker.string_list(review["sampling"]["riskCodes"], "risk codes"))
    rows = review["members"]
    need(isinstance(rows, list) and len(rows) == len(env["members"]), "batch_members", "Review must explicitly distinguish every sampled/unsampled member")
    expected = {r["code"]:r for r in env["members"]}; seen = set(); sampled = set(); selected = None
    excluded = set(checker.string_list(review.get("excludedCodes", []), "excluded codes"))
    need(excluded < set(expected), "batch_exclusions", "Exclusions must be batch members and leave an eligible subset")
    for row in rows:
        checker.shape(row, {"code", "bundlePath", "manifestSha256", "contentSampled", "reviewedClaimIds"}, {"checks"}, "batch review member")
        code = row["code"]
        need(code in expected and code not in seen and all(row[k] == expected[code][k] for k in ("bundlePath", "manifestSha256")), "batch_members", "Review member identity/hash mismatch")
        seen.add(code)
        need(type(row["contentSampled"]) is bool, "batch_review_scope", "Sampling flag must be boolean")
        ids = checker.string_list(row["reviewedClaimIds"], "actually reviewed claims", nonempty=row["contentSampled"])
        if row["contentSampled"]:
            sampled.add(code)
            folder = Path(root) / row["bundlePath"]
            member_reader = checker.parse_json(read_regular(folder / "reader.json"), "sample reader")
            member_evidence = checker.parse_json(read_regular(folder / "evidence.json"), "sample evidence")
            known = {r["id"].strip() for r in member_evidence["claims"]}
            need(set(ids) <= known, "review_claim", "Unknown sampled claim")
            approved = review["contentDecision"] == "approved" and code not in excluded
            if approved:
                need(checker.reader_claim_ids(member_reader) <= set(ids), "review_coverage", "Sampled companies require full used-claim coverage")
            if code in excluded:
                # A targeted failure is enough to exclude. Omit unperformed checks;
                # do not force the reviewer to invent a full factual examination.
                checker.shape(row.get("checks"), set(), L_CHECKS, "excluded member checks")
                for key, check in row["checks"].items():
                    checker.shape(check, {"decision", "reason"}, set(), "excluded member check." + key)
                    need(check["decision"] in {"passed", "needs_revision"}, "review_checks", "Unknown targeted review decision")
                    checker.text(check["reason"], "excluded member check reason")
                need(any(check["decision"] == "needs_revision" for check in row["checks"].values()), "batch_exclusions", "Excluded member needs an actual failed check with its reason")
            else:
                validate_l_review_fields({"contentTier":"L", "reviewer":reviewer, "checks":row.get("checks")}, member_reader, {"producer":env["producer"]}, approved)
        else:
            need(code not in excluded, "batch_exclusions", "Exclusion requires a real sampled finding, not an unreviewed omission")
            need(not ids and "checks" not in row, "batch_review_scope", "Unsampled companies cannot claim independent claim/check coverage")
        if row["bundlePath"] == bundle_path:
            selected = row
    need(bool(sampled) and risk <= sampled, "batch_sampling", "At least one independent sample and all declared risks must be reviewed")
    need(review["contentDecision"] != "approved" or bool(sampled - excluded), "batch_sampling", "Eligible subset needs at least one passed independent sample")
    need(selected is not None and selected["manifestSha256"] == receipt["manifestSha256"] and expected[selected["code"]]["readySha256"] == receipt["readySha256"], "batch_members", "Package is absent from this batch approval")
    # Compact machine view of one member, never an individual review document.
    return _batch_member_view(review, env, selected, receipt, bundle_path)


def load_payload(bundle, receipt):
    bodies = {}
    for name in ("reader.json", "evidence.json", "sources.json", "ready.json"):
        raw = read_regular(bundle / name)
        expected = receipt["readySha256"] if name == "ready.json" else receipt["verifiedPayloadHashes"][name]
        need(sha(raw) == expected, "input_drift", "Selected input bytes no longer match the validated package")
        bodies[name] = raw
    return bodies


def render_html(bodies):
    reader, evidence, sources = (checker.parse_json(bodies[n], n) for n in ("reader.json", "evidence.json", "sources.json"))
    e = lambda value: html.escape(str(value), quote=True)
    claims = {row["id"].strip(): row for row in evidence["claims"]}
    source_map = {row["id"].strip(): row for row in sources["sources"]}
    answers = {row["questionId"]: row for row in reader["answers"]}
    def evidence_details(claim_ids):
        details = []
        for cid in claim_ids:
            claim = claims[cid.strip()]
            citations = []
            for cite in claim["citations"]:
                source = source_map[cite["sourceId"].strip()]
                checker.source_url(source["url"], "source.url")
                page = " · PDF 第 " + e(cite["pdfPage"]) + " 页" if "pdfPage" in cite else ""
                citations.append('<li><a href="' + e(source["url"]) + '" target="_blank" rel="noopener noreferrer">' + e(source["title"]) + '</a><p class="location">' + e(cite["section"]) + page + '</p><blockquote>' + e(cite["excerpt"]) + '</blockquote></li>')
            limitation = claim.get("limitations", [])
            if isinstance(limitation, str):
                limitation = [limitation]
            limits = ''.join('<p class="boundary">边界：' + e(item) + '</p>' for item in limitation)
            details.append('<div class="claim"><p><span class="kind">' + e(TYPES[claim["claimType"]]) + '</span> ' + e(claim["claim"]) + '</p><ul>' + ''.join(citations) + '</ul>' + limits + '</div>')
        return '<details><summary>查看依据与边界</summary>' + ''.join(details) + '</details>' if details else ''
